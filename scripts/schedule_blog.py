#!/usr/bin/env python3
"""Give every post in content/blog/plan.json a publish_at: one post per day, at a random time.

Posts go out in the order they are listed in plan.json, one per day from the plan's
"start" date. Times are in Perth time (AWST, UTC+8, no daylight saving) and are chosen
from three reading windows (before work, lunch, evening) so the time of day changes
from day to day. No two consecutive days land within 45 minutes of each other.

    python3 scripts/schedule_blog.py            # reschedule everything (seed 20261019)
    python3 scripts/schedule_blog.py --seed 7   # a different set of random times

Also rewrites content/blog/SCHEDULE.md, a readable calendar.
"""
import argparse
import json
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "content" / "blog" / "plan.json"
CALENDAR = ROOT / "content" / "blog" / "SCHEDULE.md"

# (start minute of day, end minute of day, weight)
WINDOWS = [(5 * 60 + 30, 8 * 60 + 30, 0.30), (11 * 60, 14 * 60, 0.25), (16 * 60 + 30, 21 * 60 + 30, 0.45)]
MIN_GAP = 45


def pick(rng: random.Random, prev: int | None) -> int:
    while True:
        lo, hi, _ = rng.choices(WINDOWS, weights=[w[2] for w in WINDOWS])[0]
        minute = rng.randint(lo, hi)
        if prev is None or abs(minute - prev) >= MIN_GAP:
            return minute


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261019)
    args = ap.parse_args()

    plan = json.loads(PLAN.read_text())
    rng = random.Random(args.seed)
    start = date.fromisoformat(plan["start"])
    prev = None
    rows = []
    for i, post in enumerate(plan["posts"]):
        day = start + timedelta(days=i)
        minute = pick(rng, prev)
        prev = minute
        post["publish_at"] = f"{day.isoformat()}T{minute // 60:02d}:{minute % 60:02d}:00+08:00"
        rows.append((day, minute, post))
    PLAN.write_text(json.dumps(plan, indent=2, ensure_ascii=False) + "\n")

    lines = [
        "# Blog publishing calendar",
        "",
        "One post a day, at a random time (Perth time, AWST). Generated by `scripts/schedule_blog.py`. Edit `publish_at` in `content/blog/plan.json` to move a post.",
        "",
        "| Day | Date | Time | Topic | Post |",
        "|---|---|---|---|---|",
    ]
    for n, (day, minute, post) in enumerate(rows, 1):
        h, m = divmod(minute, 60)
        t = f"{(h % 12) or 12}:{m:02d} {'am' if h < 12 else 'pm'}"
        lines.append(f"| {n} | {day.strftime('%a')} {day.day} {day.strftime('%b %Y')} | {t} | {post['pillar']} | `{post['slug']}` |")
    CALENDAR.write_text("\n".join(lines) + "\n")
    print(f"scheduled {len(rows)} posts, {rows[0][0]} to {rows[-1][0]}")


if __name__ == "__main__":
    main()
